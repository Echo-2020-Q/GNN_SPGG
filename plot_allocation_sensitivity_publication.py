def _resolve_serif_font() -> str:
    available_fonts = {entry.name for entry in font_manager.fontManager.ttflist}
    for candidate in ("Times New Roman", "Times", "Nimbus Roman", "DejaVu Serif"):
        if candidate in available_fonts:
            return candidate
    return "DejaVu Serif"


def _configure_publication_style() -> None:
    serif_font = _resolve_serif_font()
    rc_params: dict[str, Any] = {
        "font.family": serif_font,
        "font.serif": [serif_font, "Times New Roman", "Times", "Nimbus Roman", "DejaVu Serif"],
        "font.weight": "bold",
        "axes.unicode_minus": False,
        "mathtext.fontset": "custom",
        "mathtext.rm": serif_font,
        "mathtext.it": f"{serif_font}:italic",
        "mathtext.bf": f"{serif_font}:bold",
        "mathtext.cal": f"{serif_font}:italic",
    }
    plt.rcParams.update(rc_params)


def _style_axis_text(
    axis: Any,
    *,
    axis_label_fontsize: float,
    x_tick_labelsize: float,
    y_tick_labelsize: float,
) -> None:
    serif_font = _resolve_serif_font()
    xlabel = axis.xaxis.get_label()
    ylabel = axis.yaxis.get_label()
    xlabel.set_fontfamily(serif_font)
    ylabel.set_fontfamily(serif_font)
    xlabel.set_fontweight("bold")
    ylabel.set_fontweight("bold")
    xlabel.set_fontsize(axis_label_fontsize)
    ylabel.set_fontsize(axis_label_fontsize)
    for tick_label in axis.get_xticklabels():
        tick_label.set_fontfamily(serif_font)
        tick_label.set_fontweight("bold")
        tick_label.set_fontsize(x_tick_labelsize)
    for tick_label in axis.get_yticklabels():
        tick_label.set_fontfamily(serif_font)
        tick_label.set_fontweight("bold")
        tick_label.set_fontsize(y_tick_labelsize)


def _load_rows(csv_path: Path) -> list[dict[str, Any]]:
    with csv_path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        rows = [dict(row) for row in reader]

    if not rows:
        raise ValueError(f"No rows found in {csv_path}")
    if "feature" not in rows[0] or "allocation_l1_mean" not in rows[0]:
        raise ValueError(f"{csv_path} does not look like a feature_importance.csv/topology_feature_importance.csv file.")
    return rows


def _optional_float(row: dict[str, Any], key: str) -> float | None:
    if key not in row or row[key] in {None, ""}:
        return None
    value = float(row[key])
    return value if math.isfinite(value) else None


def _select_paper_rows(rows: list[dict[str, Any]], *, error_bar_mode: str) -> list[dict[str, Any]]:
    selected: list[dict[str, Any]] = []
    has_topology_rows = any("topology" in row for row in rows)
    for feature_key in PAPER_FEATURE_ORDER:
        matching_rows = [row for row in rows if str(row.get("feature")) == feature_key]
        if not matching_rows:
            continue

        if has_topology_rows:
            values = np.asarray([float(row["allocation_l1_mean"]) for row in matching_rows], dtype=np.float64)
            values = values[np.isfinite(values)]
            if values.size == 0:
                continue
            mean_value = float(np.mean(values))
            std_value = float(np.std(values, ddof=0)) if values.size > 1 else 0.0
            sem_value = float(std_value / np.sqrt(values.size)) if values.size > 0 else 0.0
            min_value = float(np.min(values))
            max_value = float(np.max(values))
            if error_bar_mode == "std":
                xerr: float | tuple[float, float] = std_value
            elif error_bar_mode == "sem":
                xerr = sem_value
            elif error_bar_mode == "range":
                xerr = (max(0.0, mean_value - min_value), max(0.0, max_value - mean_value))
            else:
                xerr = 0.0
            enriched = {
                "feature": feature_key,
                "paper_label": PAPER_FEATURE_LABELS[feature_key],
                "allocation_l1_mean": mean_value,
                "allocation_l1_std": std_value,
                "allocation_l1_sem": sem_value,
                "allocation_l1_min": min_value,
                "allocation_l1_max": max_value,
                "allocation_l1_xerr": xerr,
                "topology_count": int(values.size),
            }
        else:
            matching_row = dict(matching_rows[0])
            mean_value = float(matching_row["allocation_l1_mean"])
            std_value = _optional_float(matching_row, "allocation_l1_std")
            sem_value = _optional_float(matching_row, "allocation_l1_sem")
            error_value = 0.0
            if error_bar_mode == "std" and std_value is not None:
                error_value = std_value
            elif error_bar_mode == "sem" and sem_value is not None:
                error_value = sem_value
            enriched = dict(matching_row)
            enriched["paper_label"] = PAPER_FEATURE_LABELS[feature_key]
            enriched["allocation_l1_mean"] = mean_value
            enriched["allocation_l1_xerr"] = error_value
        selected.append(enriched)

    if not selected:
        raise ValueError("None of the requested paper features were found in the CSV.")

    selected.sort(key=lambda row: float(row["allocation_l1_mean"]), reverse=True)
    return selected


def _resolve_output_targets(output_arg: Path | None, input_path: Path) -> list[Path]:
    if output_arg is None:
        stem_path = input_path.parent / "allocation_sensitivity_publication"
        return [stem_path.with_suffix(".png"), stem_path.with_suffix(".pdf")]

    if output_arg.suffix.lower() in {".png", ".pdf", ".svg"}:
        return [output_arg.expanduser().resolve()]

    stem_path = output_arg.expanduser().resolve()
    return [stem_path.with_suffix(".png"), stem_path.with_suffix(".pdf")]


def render_figure(
    rows: list[dict[str, Any]],
    title: str,
    x_label: str,
    output_targets: list[Path],
    dpi: int,
) -> None:
    _configure_publication_style()

    labels = [str(row["paper_label"]) for row in rows]
    scores = [float(row["allocation_l1_mean"]) for row in rows]
    xerr_values = [row.get("allocation_l1_xerr", 0.0) for row in rows]
    asymmetric_errors = [
        (
            float(value[0]) if isinstance(value, tuple) else float(value),
            float(value[1]) if isinstance(value, tuple) else float(value),
        )
        for value in xerr_values
    ]
    has_errors = any(left > 0.0 or right > 0.0 for left, right in asymmetric_errors)
    bar_xerr: Any = None
    if has_errors:
        if any(isinstance(value, tuple) for value in xerr_values):
            bar_xerr = [
                [left for left, _ in asymmetric_errors],
                [right for _, right in asymmetric_errors],
            ]
        else:
            bar_xerr = [float(value) for value in xerr_values]
    positions = list(range(len(labels)))
    xmax = max((score + right for score, (_, right) in zip(scores, asymmetric_errors)), default=0.0)
    x_padding = xmax * 0.12 if xmax > 0.0 else 1.0
    bar_fill_color = str(SCRIPT_DEFAULTS["bar_fill_color"])
    bar_edge_color = str(SCRIPT_DEFAULTS["bar_edge_color"])
    error_bar_color = str(SCRIPT_DEFAULTS["error_bar_color"])
    grid_color = str(SCRIPT_DEFAULTS["grid_color"])
    spine_color = str(SCRIPT_DEFAULTS["spine_color"])
    text_color = str(SCRIPT_DEFAULTS["text_color"])
    title_fontsize = float(SCRIPT_DEFAULTS["title_fontsize"])
    axis_label_fontsize = float(SCRIPT_DEFAULTS["axis_label_fontsize"])
    tick_label_fontsize = float(SCRIPT_DEFAULTS["tick_label_fontsize"])
    feature_label_fontsize = float(SCRIPT_DEFAULTS["feature_label_fontsize"])

    figure, axis = plt.subplots(figsize=(4, 4), constrained_layout=True)
    axis.barh(
        positions,
        scores,
        xerr=bar_xerr,
        color=bar_fill_color,
        edgecolor=bar_edge_color,
        linewidth=0.9,
        height=0.62,
        ecolor=error_bar_color,
        capsize=3 if has_errors else 0,
        error_kw={"elinewidth": 1.0, "capthick": 1.0},
    )

    axis.set_yticks(positions)
    axis.set_yticklabels(labels, fontsize=feature_label_fontsize, color=text_color, fontweight="bold")
    axis.invert_yaxis()
    axis.set_xlabel(x_label, fontsize=axis_label_fontsize, color=text_color, fontweight="bold")
    if title.strip():
        axis.set_title(title, fontsize=title_fontsize, color=text_color, pad=10)

    axis.set_axisbelow(True)
    axis.grid(axis="x", color=grid_color, linewidth=0.8)
    axis.tick_params(axis="x", labelsize=tick_label_fontsize, colors=text_color)
    axis.tick_params(axis="y", length=0)
    _style_axis_text(
        axis,
        axis_label_fontsize=axis_label_fontsize,
        x_tick_labelsize=tick_label_fontsize,
        y_tick_labelsize=feature_label_fontsize,
    )
    axis.set_xlim(0.0, xmax + x_padding)

    for spine_name in ("top", "right", "left", "bottom"):
        axis.spines[spine_name].set_visible(True)
        axis.spines[spine_name].set_color(spine_color)
        axis.spines[spine_name].set_linewidth(0.8)

    for output_path in output_targets:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        save_kwargs: dict[str, Any] = {"bbox_inches": "tight", "facecolor": "white"}
        if output_path.suffix.lower() == ".png":
            save_kwargs["dpi"] = max(72, int(dpi))
        figure.savefig(output_path, **save_kwargs)

    plt.close(figure)


def main() -> None:
    args = parse_args()
    input_path = args.input.expanduser().resolve()
    if not input_path.exists():
        raise FileNotFoundError(f"Input CSV not found: {input_path}")

    raw_rows = _load_rows(input_path)
    paper_rows = _select_paper_rows(raw_rows, error_bar_mode=str(args.error_bar_mode))
    output_targets = _resolve_output_targets(args.output, input_path)
    render_figure(
        paper_rows,
        title=args.title,
        x_label=args.x_label,
        output_targets=output_targets,
        dpi=int(args.dpi),
    )

    print(f"Saved publication figure to: {', '.join(str(path) for path in output_targets)}")
    print("Included features:", ", ".join(str(row["feature"]) for row in paper_rows))


if __name__ == "__main__":
    main()
